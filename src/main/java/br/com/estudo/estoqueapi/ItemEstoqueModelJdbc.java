package br.com.estudo.estoqueapi;

import java.sql.PreparedStatement;
import java.sql.Statement;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import org.springframework.context.annotation.Profile;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.stereotype.Repository;

@Repository
@Profile("persistente")
public class ItemEstoqueModelJdbc implements ItemEstoqueModel {
    private final JdbcTemplate jdbc;

    public ItemEstoqueModelJdbc(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
        jdbc.execute("""
            CREATE TABLE IF NOT EXISTS itens (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome VARCHAR(120) NOT NULL,
                quantidade INTEGER NOT NULL CHECK (quantidade >= 0),
                preco DECIMAL(11,2) NOT NULL CHECK (preco >= 0)
            )
            """);
    }

    private List<ItemEstoque> consultar(String sql, Object... argumentos) {
        return jdbc.query(sql, (rs, row) -> new ItemEstoque(rs.getLong("id"),
            rs.getString("nome"), rs.getInt("quantidade"), rs.getBigDecimal("preco")), argumentos);
    }

    public ItemEstoque criar(ItemEstoque entrada) {
        GeneratedKeyHolder chave = new GeneratedKeyHolder();
        jdbc.update(connection -> {
            PreparedStatement statement = connection.prepareStatement(
                "INSERT INTO itens (nome, quantidade, preco) VALUES (?, ?, ?)", Statement.RETURN_GENERATED_KEYS);
            statement.setString(1, entrada.getNome());
            statement.setInt(2, entrada.getQuantidade());
            statement.setBigDecimal(3, entrada.getPreco());
            return statement;
        }, chave);
        if (chave.getKey() == null) throw new IllegalStateException("ID do item não gerado");
        return new ItemEstoque(chave.getKey().longValue(), entrada.getNome(), entrada.getQuantidade(), entrada.getPreco());
    }

    public List<ItemEstoque> listar(String nome) {
        if (nome == null || nome.isBlank()) return consultar("SELECT * FROM itens ORDER BY id");
        // LOCATE trata %, _ e outros caracteres como parte do nome, sem curingas SQL.
        return consultar("SELECT * FROM itens WHERE LOCATE(?, LOWER(nome)) > 0 ORDER BY id", nome.strip().toLowerCase(Locale.ROOT));
    }

    public Optional<ItemEstoque> buscar(Long id) {
        return consultar("SELECT * FROM itens WHERE id = ?", id).stream().findFirst();
    }

    public Optional<ItemEstoque> atualizar(Long id, ItemEstoque entrada) {
        int alterados = jdbc.update("UPDATE itens SET nome = ?, quantidade = ?, preco = ? WHERE id = ?",
            entrada.getNome(), entrada.getQuantidade(), entrada.getPreco(), id);
        return alterados == 0 ? Optional.empty() : Optional.of(new ItemEstoque(id, entrada.getNome(), entrada.getQuantidade(), entrada.getPreco()));
    }

    public boolean excluir(Long id) {
        return jdbc.update("DELETE FROM itens WHERE id = ?", id) > 0;
    }
}
